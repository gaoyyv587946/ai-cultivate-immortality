def get_prelude_step(step_index: int) -> dict:
    """获取指定序章步骤的剧情"""
    if 0 <= step_index < len(PRELUDE_STEPS):
        return PRELUDE_STEPS[step_index]
    return None


def get_prelude_step_count() -> int:
    """获取序章总步数"""
    return len(PRELUDE_STEPS)


def get_breakthrough_story(realm_level: int, success: bool) -> str:
    """获取突破剧情文本"""
    if realm_level in BREAKTHROUGH_STORIES:
        key = "success" if success else "fail"
        return BREAKTHROUGH_STORIES[realm_level][key]
    return "你成功突破了！" if success else "你突破失败了。"


def get_death_scene(death_type: str) -> str:
    """获取死亡结局文本"""
    return DEATH_SCENES.get(death_type, DEATH_SCENES["意外"])
